function detectLang() {
  const saved = localStorage.getItem('vm_lang');
  if (saved === 'ru' || saved === 'en') return saved;
  const l = (navigator.language || 'en').toLowerCase();
  return /^(ru|uk|be|kk)/.test(l) ? 'ru' : 'en';
}

let LANG = detectLang();
document.documentElement.lang = LANG;

function t(key, ...args) {
  const val = (T[LANG] && T[LANG][key]) ?? T.ru[key];
  if (typeof val === 'function') return val(...args);
  return val ?? key;
}

function setLang(l) {
  if (l !== 'ru' && l !== 'en') return;
  localStorage.setItem('vm_lang', l);
  location.reload();
}

function toggleLang() {
  setLang(LANG === 'ru' ? 'en' : 'ru');
}

function applyI18n(root) {
  root = root || document;
  root.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (typeof val === 'string') el.textContent = val;
  });
  root.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    const val = t(key);
    if (typeof val === 'string') el.innerHTML = val;
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const val = t(key);
    if (typeof val === 'string') el.placeholder = val;
  });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const val = t(key);
    if (typeof val === 'string') el.title = val;
  });
  // <title> tag if marked
  const titleEl = document.querySelector('title[data-i18n]');
  if (titleEl) {
    const k = titleEl.getAttribute('data-i18n');
    const v = t(k);
    if (v) document.title = v;
  }
}
